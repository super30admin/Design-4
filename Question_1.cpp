#include<unordered_map>
#include<unordered_set>
#include<vector>
#include<queue>
#include<iostream>
using namespace std;
class Twitter {
    int timestamp;
    unordered_map<int,vector<pair<int,int>>>postsByUser;
    unordered_map<int,unordered_set<int>>followerGraph;
public:
    Twitter() {
        timestamp = 0;
    }
    
    void postTweet(int userId, int tweetId) {
        postsByUser[userId].push_back({tweetId,timestamp});
        timestamp++;
    }
    
    vector<int> getNewsFeed(int userId) {
        priority_queue<vector<int>>heap;
        followerGraph[userId].insert(userId);
        for(auto follow:followerGraph[userId]){
            if(postsByUser.find(follow)==postsByUser.end()) continue; 
            heap.push({postsByUser[follow].back().second,postsByUser[follow].back().first,(int)postsByUser[follow].size()-1,follow});
        }
        vector<int>feed;
        int t=1;
        while(t<=10&&!heap.empty()){
            vector<int>top = heap.top();
            heap.pop();
            feed.push_back(top[1]);
            if(top[2]){
                heap.push({postsByUser[top[3]][top[2]-1].second,postsByUser[top[3]][top[2]-1].first,top[2]-1,top[3]});
            }
            t++;
        }
        followerGraph[userId].erase(userId);
        return feed;
    }
    
    void follow(int followerId, int followeeId) {
        followerGraph[followerId].insert(followeeId);
    }
    
    void unfollow(int followerId, int followeeId) {
        followerGraph[followerId].erase(followeeId);
    }
};
int main() {
    Twitter* twitter = new Twitter();
    twitter->postTweet(1, 5);
    vector<int> feed1 = twitter->getNewsFeed(1);
    cout << "News Feed for User 1: ";
    for (int tweetId : feed1) {
        cout << tweetId << " ";
    }
    cout << endl; // Output: 5
    twitter->follow(1, 2);
    twitter->postTweet(2, 6);
    vector<int> feed2 = twitter->getNewsFeed(1);
    cout << "News Feed for User 1 after following User 2: ";
    for (int tweetId : feed2) {
        cout << tweetId << " ";
    }
    cout << endl; // Output: 6 5
    twitter->unfollow(1, 2);
    vector<int> feed3 = twitter->getNewsFeed(1);
    cout << "News Feed for User 1 after unfollowing User 2: ";
    for (int tweetId : feed3) {
        cout << tweetId << " ";
    }
    cout << endl; // Output: 5
    return 0;
}
